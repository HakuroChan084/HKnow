/// Ngôn ngữ giao diện: Tiếng Việt (gốc), English, Русский. Mặc định theo ngôn ngữ hệ thống, đổi tay trong bảng điều khiển.
enum AppLang: String, CaseIterable {
    case vi, en, ru

    private static let key = "gfnweb.lang.v1"

    /// Mặc định: English (đổi tay trong cài đặt)
    static var system: AppLang { .en }

    static var current: AppLang {
        get {
            if let s = UserDefaults.standard.string(forKey: key), let l = AppLang(rawValue: s) { return l }
            return system
        }
        set { UserDefaults.standard.set(newValue.rawValue, forKey: key) }
    }

    var nativeName: String {
        switch self {
        case .vi: return "Tiếng Việt"
        case .en: return "English"
        case .ru: return "Русский"
        }
    }
}

/// Dịch một chuỗi giao diện. Khóa là chuỗi tiếng Việt gốc; thiếu bản dịch thì giữ nguyên tiếng Việt.
func L(_ vi: String) -> String {
    switch AppLang.current {
    case .vi: return vi
    case .en: return L10n.en[vi] ?? vi
    case .ru: return L10n.ru[vi] ?? vi
    }
}

