package com.hknow.app

import android.content.Context
import java.util.Locale

/** Ngôn ngữ giao diện: Tiếng Việt (gốc), English, Русский. Mặc định theo hệ thống, đổi tay trong menu. */
enum class Lang(val code: String, val nativeName: String) {
    VI("vi", "Tiếng Việt"), EN("en", "English"), RU("ru", "Русский");

    companion object {
        private const val PREFS = "hknow.lang"
        private const val KEY = "lang.v1"
        private var override: Lang? = null
        private var loaded = false

        private fun system(): Lang {
            val c = Locale.getDefault().language.lowercase()
            return when { c.startsWith("vi") -> VI; c.startsWith("ru") -> RU; else -> EN }
        }

        fun load(context: Context) {
            val code = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY, null)
            override = values().firstOrNull { it.code == code }
            loaded = true
        }

        val current: Lang get() = override ?: system()

        fun set(context: Context, lang: Lang) {
            override = lang
            context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putString(KEY, lang.code).apply()
        }
    }
}

/** Dịch một chuỗi giao diện. Khóa là chuỗi tiếng Việt gốc; thiếu bản dịch thì giữ nguyên tiếng Việt. */
fun L(vi: String): String = when (Lang.current) {
    Lang.VI -> vi
    Lang.EN -> L10n.en[vi] ?: vi
    Lang.RU -> L10n.ru[vi] ?: vi
}

